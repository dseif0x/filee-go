// rect is a box in points, y up.
type rect struct{ Left, Bottom, Right, Top float64 }

func (r rect) Width() float64  { return r.Right - r.Left }
func (r rect) Height() float64 { return r.Top - r.Bottom }

// letter is one character of a page (PDF space, y up).
type letter struct {
	Text string
	Box  rect
	// Loose is the box of the glyph's advance and the font's height.
	Loose     rect
	OriginX   float64
	OriginY   float64
	Size      float64
	Font      string
	Bold      bool
	Italic    bool
	Color     string
	Invisible bool
	// Horizontal text, upright (not turned, not vertical).
	Horizontal bool
	// Space is whitespace or a line end, real or generated by PDFium.
	Space bool
}

type pageLink struct {
	Box rect
	URI string
}

// pathPoint is a point of a subpath; Curve marks the end of a curve.
type pathPoint struct {
	X, Y  float64
	Curve bool
}

type pagePath struct {
	Stroked, Filled bool
	StrokeColor     string
	FillColor       string
	LineWidth       float64
	Dashed          bool
	// Subpaths: each a list of points, the first a move; Closed per subpath.
	Subpaths [][]pathPoint
	Closed   []bool
}

type pageImage struct {
	Box     rect
	obj     references.FPDF_PAGEOBJECT
	Jpeg    []byte // the stream as it is, when it is a plain JPEG
	IsMask  bool
	Width   int
	Height  int
	Filters []string
}

type pageData struct {
	Index    int
	Crop     rect
	Rotation int // degrees clockwise
	Letters  []letter
	Links    []pageLink
	Paths    []pagePath
	Images   []pageImage
	// TooManySegments: a drawing (map, chart) rather than a form.
	TooManySegments bool
}

func hexColor(r, g, b uint) string { return fmt.Sprintf("#%02X%02X%02X", r&0xFF, g&0xFF, b&0xFF) }

// readPageData reads one page. withGraphics adds paths and pictures.
func (d *pdfDoc) readPageData(index int, withGraphics bool) (*pageData, error) {
	page := d.page(index)
	pd := &pageData{Index: index}
	if r, err := d.p.FPDFPage_GetRotation(&requests.FPDFPage_GetRotation{Page: page}); err == nil {
		pd.Rotation = int(r.PageRotation) * 90
	}
	if b, err := d.p.FPDFPage_GetCropBox(&requests.FPDFPage_GetCropBox{Page: page}); err == nil {
		pd.Crop = rect{float64(min(b.Left, b.Right)), float64(min(b.Bottom, b.Top)), float64(max(b.Left, b.Right)), float64(max(b.Bottom, b.Top))}
	} else if b, err := d.p.FPDFPage_GetMediaBox(&requests.FPDFPage_GetMediaBox{Page: page}); err == nil {
		pd.Crop = rect{float64(min(b.Left, b.Right)), float64(min(b.Bottom, b.Top)), float64(max(b.Left, b.Right)), float64(max(b.Bottom, b.Top))}
	} else {
		w, h, err := d.PageSize(index)
		if err != nil {
			return nil, err
		}
		pd.Crop = rect{0, 0, w, h}
	}
	if err := d.readLetters(page, pd); err != nil {
		return nil, err
	}
	d.readLinks(page, pd)
	if withGraphics {
		d.readObjects(page, pd)
	}
	return pd, nil
}

type textObjectInfo struct {
	font         string
	bold, italic bool
	color        string
	invisible    bool
	fillStroke   bool
}

func (d *pdfDoc) readLetters(page requests.Page, pd *pageData) error {
	tp, err := d.p.FPDFText_LoadPage(&requests.FPDFText_LoadPage{Page: page})
	if err != nil {
		return err
	}
	defer d.p.FPDFText_ClosePage(&requests.FPDFText_ClosePage{TextPage: tp.TextPage})
	text := tp.TextPage
	count, err := d.p.FPDFText_CountChars(&requests.FPDFText_CountChars{TextPage: text})
	if err != nil {
		return err
	}
	objects := map[references.FPDF_PAGEOBJECT]*textObjectInfo{}
	pd.Letters = make([]letter, 0, count.Count)
	for i := 0; i < count.Count; i++ {
		u, err := d.p.FPDFText_GetUnicode(&requests.FPDFText_GetUnicode{TextPage: text, Index: i})
		if err != nil {
			continue
		}
		r := rune(u.Unicode)
		l := letter{Text: string(r)}
		if r == 0 || unicode.IsSpace(r) || r == 0xFFFE {
			l.Space = true
			l.Text = " "
			pd.Letters = append(pd.Letters, l)
			continue
		}
		if g, err := d.p.FPDFText_IsGenerated(&requests.FPDFText_IsGenerated{TextPage: text, Index: i}); err == nil && g.IsGenerated {
			l.Space = true
			pd.Letters = append(pd.Letters, l)
			continue
		}
		if b, err := d.p.FPDFText_GetCharBox(&requests.FPDFText_GetCharBox{TextPage: text, Index: i}); err == nil {
			l.Box = rect{b.Left, b.Bottom, b.Right, b.Top}
		}
		l.Loose = l.Box
		if b, err := d.p.FPDFText_GetLooseCharBox(&requests.FPDFText_GetLooseCharBox{TextPage: text, Index: i}); err == nil {
			r := b.Rect
			l.Loose = rect{float64(min(r.Left, r.Right)), float64(min(r.Bottom, r.Top)), float64(max(r.Left, r.Right)), float64(max(r.Bottom, r.Top))}
		}
		if o, err := d.p.FPDFText_GetCharOrigin(&requests.FPDFText_GetCharOrigin{TextPage: text, Index: i}); err == nil {
			l.OriginX, l.OriginY = o.X, o.Y
		}
		size := 0.0
		if s, err := d.p.FPDFText_GetFontSize(&requests.FPDFText_GetFontSize{TextPage: text, Index: i}); err == nil {
			size = s.FontSize
		}
		l.Horizontal = true
		if m, err := d.p.FPDFText_GetMatrix(&requests.FPDFText_GetMatrix{TextPage: text, Index: i}); err == nil {
			a, b, c, dd := float64(m.Matrix.A), float64(m.Matrix.B), float64(m.Matrix.C), float64(m.Matrix.D)
			// The size as drawn: the font size scaled by the text matrix.
			if scale := math.Hypot(c, dd); scale > 0 {
				size *= scale
			}
			l.Horizontal = a > 0 && math.Abs(b) <= 0.05*math.Abs(a)
		}
		l.Size = size
		obj, err := d.p.FPDFText_GetTextObject(&requests.FPDFText_GetTextObject{TextPage: text, Index: i})
		var info *textObjectInfo
		if err == nil {
			info = objects[obj.TextObject]
		}
		if info == nil {
			info = &textObjectInfo{}
			if f, err := d.p.FPDFText_GetFontInfo(&requests.FPDFText_GetFontInfo{TextPage: text, Index: i}); err == nil {
				info.font = f.FontName
				info.bold = f.Flags&(1<<18) != 0
				info.italic = f.Flags&(1<<6) != 0
			}
			if w, err := d.p.FPDFText_GetFontWeight(&requests.FPDFText_GetFontWeight{TextPage: text, Index: i}); err == nil && w.FontWeight >= 600 {
				info.bold = true
			}
			if c, err := d.p.FPDFText_GetFillColor(&requests.FPDFText_GetFillColor{TextPage: text, Index: i}); err == nil {
				info.color = hexColor(c.R, c.G, c.B)
			}
			if err == nil {
				if m, err := d.p.FPDFTextObj_GetTextRenderMode(&requests.FPDFTextObj_GetTextRenderMode{PageObject: obj.TextObject}); err == nil {
					info.invisible = m.TextRenderMode == enums.FPDF_TEXTRENDERMODE_INVISIBLE
					info.fillStroke = m.TextRenderMode == enums.FPDF_TEXTRENDERMODE_FILL_STROKE
				}
				objects[obj.TextObject] = info
			}
		}
		l.Font, l.Bold, l.Italic, l.Color, l.Invisible = info.font, info.bold || info.fillStroke, info.italic, info.color, info.invisible
		pd.Letters = append(pd.Letters, l)
	}
	return nil
}

func (d *pdfDoc) readLinks(page requests.Page, pd *pageData) {
	start := 0
	for n := 0; n < 10000; n++ {
		e, err := d.p.FPDFLink_Enumerate(&requests.FPDFLink_Enumerate{Page: page, StartPos: start})
		if err != nil || e.Link == nil {
			return
		}
		if e.NextStartPos == nil {
			return
		}
		start = *e.NextStartPos
		a, err := d.p.FPDFLink_GetAction(&requests.FPDFLink_GetAction{Link: *e.Link})
		if err != nil || a.Action == nil {
			continue
		}
		t, err := d.p.FPDFAction_GetType(&requests.FPDFAction_GetType{Action: *a.Action})
		if err != nil || t.Type != enums.FPDF_ACTION_ACTION_URI {
			continue
		}
		u, err := d.p.FPDFAction_GetURIPath(&requests.FPDFAction_GetURIPath{Document: d.doc, Action: *a.Action})
		if err != nil || u.URIPath == nil {
			continue
		}
		uri := strings.TrimSpace(*u.URIPath)
		lower := strings.ToLower(uri)
		if !strings.HasPrefix(lower, "http://") && !strings.HasPrefix(lower, "https://") && !strings.HasPrefix(lower, "mailto:") {
			continue
		}
		r, err := d.p.FPDFLink_GetAnnotRect(&requests.FPDFLink_GetAnnotRect{Link: *e.Link})
		if err != nil || r.Rect == nil {
			continue
		}
		pd.Links = append(pd.Links, pageLink{
			Box: rect{float64(min(r.Rect.Left, r.Rect.Right)), float64(min(r.Rect.Bottom, r.Rect.Top)), float64(max(r.Rect.Left, r.Rect.Right)), float64(max(r.Rect.Bottom, r.Rect.Top))},
			URI: uri,
		})
	}
}

// maxSegments: pages with more line segments are drawings (maps, charts), not forms.
const maxSegments = 5000

type objMatrix struct{ a, b, c, d, e, f float64 }

func (m objMatrix) apply(x, y float64) (float64, float64) {
	return m.a*x + m.c*y + m.e, m.b*x + m.d*y + m.f
}

// then is m applied first, then o.
func (m objMatrix) then(o objMatrix) objMatrix {
	return objMatrix{
		m.a*o.a + m.b*o.c, m.a*o.b + m.b*o.d,
		m.c*o.a + m.d*o.c, m.c*o.b + m.d*o.d,
		m.e*o.a + m.f*o.c + o.e, m.e*o.b + m.f*o.d + o.f,
	}
}

func fromFS(m structs.FPDF_FS_MATRIX) objMatrix {
	return objMatrix{float64(m.A), float64(m.B), float64(m.C), float64(m.D), float64(m.E), float64(m.F)}
}

func (d *pdfDoc) readObjects(page requests.Page, pd *pageData) {
	n, err := d.p.FPDFPage_CountObjects(&requests.FPDFPage_CountObjects{Page: page})
	if err != nil {
		return
	}
	segments := 0
	for i := 0; i < n.Count; i++ {
		o, err := d.p.FPDFPage_GetObject(&requests.FPDFPage_GetObject{Page: page, Index: i})
		if err != nil {
			continue
		}
		d.readObject(page, o.PageObject, objMatrix{1, 0, 0, 1, 0, 0}, pd, &segments, 0)
	}
}

func (d *pdfDoc) readObject(page requests.Page, obj references.FPDF_PAGEOBJECT, parent objMatrix, pd *pageData, segments *int, depth int) {
	t, err := d.p.FPDFPageObj_GetType(&requests.FPDFPageObj_GetType{PageObject: obj})
	if err != nil {
		return
	}
	switch t.Type {
	case enums.FPDF_PAGEOBJ_FORM:
		if depth > 12 {
			return
		}
		m := objMatrix{1, 0, 0, 1, 0, 0}
		if r, err := d.p.FPDFPageObj_GetMatrix(&requests.FPDFPageObj_GetMatrix{PageObject: obj}); err == nil {
			m = fromFS(r.Matrix)
		}
		c, err := d.p.FPDFFormObj_CountObjects(&requests.FPDFFormObj_CountObjects{PageObject: obj})
		if err != nil {
			return
		}
		for i := 0; i < c.Count; i++ {
			child, err := d.p.FPDFFormObj_GetObject(&requests.FPDFFormObj_GetObject{PageObject: obj, Index: uint64(i)})
			if err == nil {
				d.readObject(page, child.PageObject, m.then(parent), pd, segments, depth+1)
			}
		}
	case enums.FPDF_PAGEOBJ_PATH:
		if pd.TooManySegments {
			return
		}
		d.readPath(obj, parent, pd, segments)
	case enums.FPDF_PAGEOBJ_IMAGE:
		if len(pd.Images) >= 200 {
			return
		}
		d.readImage(page, obj, pd)
	}
}

func (d *pdfDoc) readPath(obj references.FPDF_PAGEOBJECT, parent objMatrix, pd *pageData, segments *int) {
	mode, err := d.p.FPDFPath_GetDrawMode(&requests.FPDFPath_GetDrawMode{PageObject: obj})
	if err != nil {
		return
	}
	p := pagePath{Stroked: mode.Stroke, Filled: mode.FillMode != enums.FPDF_FILLMODE_NONE}
	if !p.Stroked && !p.Filled {
		return
	}
	if p.Stroked {
		if c, err := d.p.FPDFPageObj_GetStrokeColor(&requests.FPDFPageObj_GetStrokeColor{PageObject: obj}); err == nil {
			p.StrokeColor = hexColor(c.StrokeColor.R, c.StrokeColor.G, c.StrokeColor.B)
			if c.StrokeColor.A == 0 {
				p.Stroked = false
			}
		} else {
			p.StrokeColor = "#000000"
		}
		if w, err := d.p.FPDFPageObj_GetStrokeWidth(&requests.FPDFPageObj_GetStrokeWidth{PageObject: obj}); err == nil {
			p.LineWidth = float64(w.StrokeWidth)
		}
		if c, err := d.p.FPDFPageObj_GetDashCount(&requests.FPDFPageObj_GetDashCount{PageObject: obj}); err == nil && c.DashCount > 0 {
			p.Dashed = true
		}
	}
	if p.Filled {
		if c, err := d.p.FPDFPageObj_GetFillColor(&requests.FPDFPageObj_GetFillColor{PageObject: obj}); err == nil {
			p.FillColor = hexColor(c.FillColor.R, c.FillColor.G, c.FillColor.B)
			if c.FillColor.A == 0 {
				p.Filled = false
			}
		} else {
			p.FillColor = "#000000"
		}
	}
	m := objMatrix{1, 0, 0, 1, 0, 0}
	if r, err := d.p.FPDFPageObj_GetMatrix(&requests.FPDFPageObj_GetMatrix{PageObject: obj}); err == nil {
		m = fromFS(r.Matrix)
	}
	m = m.then(parent)
	// Line widths scale with the matrix too.
	p.LineWidth *= math.Sqrt(math.Abs(m.a*m.d - m.b*m.c))
	n, err := d.p.FPDFPath_CountSegments(&requests.FPDFPath_CountSegments{PageObject: obj})
	if err != nil {
		return
	}
	*segments += n.Count
	if *segments > maxSegments {
		pd.TooManySegments = true
		pd.Paths = nil
		return
	}
	var current []pathPoint
	closed := false
	flush := func() {
		if len(current) > 0 {
			p.Subpaths = append(p.Subpaths, current)
			p.Closed = append(p.Closed, closed)
		}
		current, closed = nil, false
	}
	for i := 0; i < n.Count; i++ {
		s, err := d.p.FPDFPath_GetPathSegment(&requests.FPDFPath_GetPathSegment{PageObject: obj, Index: i})
		if err != nil {
			continue
		}
		pt, err := d.p.FPDFPathSegment_GetPoint(&requests.FPDFPathSegment_GetPoint{PathSegment: s.PathSegment})
		if err != nil {
			continue
		}
		typ, err := d.p.FPDFPathSegment_GetType(&requests.FPDFPathSegment_GetType{PathSegment: s.PathSegment})
		if err != nil {
			continue
		}
		x, y := m.apply(float64(pt.X), float64(pt.Y))
		switch typ.Type {
		case enums.FPDF_SEGMENT_MOVETO:
			flush()
			current = []pathPoint{{X: x, Y: y}}
		case enums.FPDF_SEGMENT_LINETO:
			current = append(current, pathPoint{X: x, Y: y})
		case enums.FPDF_SEGMENT_BEZIERTO:
			current = append(current, pathPoint{X: x, Y: y, Curve: true})
		}
		if c, err := d.p.FPDFPathSegment_GetClose(&requests.FPDFPathSegment_GetClose{PathSegment: s.PathSegment}); err == nil && c.IsClose {
			closed = true
		}
	}
	flush()
	if len(p.Subpaths) > 0 {
		pd.Paths = append(pd.Paths, p)
	}
}

func (d *pdfDoc) readImage(page requests.Page, obj references.FPDF_PAGEOBJECT, pd *pageData) {
	b, err := d.p.FPDFPageObj_GetBounds(&requests.FPDFPageObj_GetBounds{PageObject: obj})
	if err != nil {
		return
	}
	img := pageImage{obj: obj, Box: rect{float64(b.Left), float64(b.Bottom), float64(b.Right), float64(b.Top)}}
	if m, err := d.p.FPDFImageObj_GetImageMetadata(&requests.FPDFImageObj_GetImageMetadata{ImageObject: obj, Page: page}); err == nil {
		md := m.ImageMetadata
		img.Width, img.Height = int(md.Width), int(md.Height)
		img.IsMask = md.BitsPerPixel == 1 && md.Colorspace == enums.FPDF_COLORSPACE_UNKNOWN
		if md.Colorspace == enums.FPDF_COLORSPACE_DEVICEGRAY || md.Colorspace == enums.FPDF_COLORSPACE_DEVICERGB {
			if c, err := d.p.FPDFImageObj_GetImageFilterCount(&requests.FPDFImageObj_GetImageFilterCount{ImageObject: obj}); err == nil {
				for i := 0; i < c.Count; i++ {
					if f, err := d.p.FPDFImageObj_GetImageFilter(&requests.FPDFImageObj_GetImageFilter{ImageObject: obj, Index: i}); err == nil {
						img.Filters = append(img.Filters, f.ImageFilter)
					}
				}
			}
			if len(img.Filters) == 1 && (img.Filters[0] == "DCTDecode" || img.Filters[0] == "DCT") {
				if raw, err := d.p.FPDFImageObj_GetImageDataRaw(&requests.FPDFImageObj_GetImageDataRaw{ImageObject: obj}); err == nil {
					if c := jpegComponents(raw.Data); c == 1 || c == 3 {
						img.Jpeg = append([]byte(nil), raw.Data...)
					}
				}
			}
		}
	}
	pd.Images = append(pd.Images, img)
}

// imagePixels decodes a picture's pixels (without its mask), or nil.
func (d *pdfDoc) imagePixels(img pageImage) image.Image {
	bm, err := d.p.FPDFImageObj_GetBitmap(&requests.FPDFImageObj_GetBitmap{ImageObject: img.obj})
	if err != nil {
		return nil
	}
	defer d.p.FPDFBitmap_Destroy(&requests.FPDFBitmap_Destroy{Bitmap: bm.Bitmap})
	w, err1 := d.p.FPDFBitmap_GetWidth(&requests.FPDFBitmap_GetWidth{Bitmap: bm.Bitmap})
	h, err2 := d.p.FPDFBitmap_GetHeight(&requests.FPDFBitmap_GetHeight{Bitmap: bm.Bitmap})
	s, err3 := d.p.FPDFBitmap_GetStride(&requests.FPDFBitmap_GetStride{Bitmap: bm.Bitmap})
	f, err4 := d.p.FPDFBitmap_GetFormat(&requests.FPDFBitmap_GetFormat{Bitmap: bm.Bitmap})
	buf, err5 := d.p.FPDFBitmap_GetBuffer(&requests.FPDFBitmap_GetBuffer{Bitmap: bm.Bitmap})
	if err1 != nil || err2 != nil || err3 != nil || err4 != nil || err5 != nil || w.Width <= 0 || h.Height <= 0 {
		return nil
	}
	width, height, stride := w.Width, h.Height, s.Stride
	if len(buf.Buffer) < stride*height {
		return nil
	}
	switch f.Format {
	case enums.FPDF_BITMAP_FORMAT_GRAY:
		out := image.NewGray(image.Rect(0, 0, width, height))
		for y := 0; y < height; y++ {
			copy(out.Pix[y*width:(y+1)*width], buf.Buffer[y*stride:])
		}
		return out
	case enums.FPDF_BITMAP_FORMAT_BGR, enums.FPDF_BITMAP_FORMAT_BGRX, enums.FPDF_BITMAP_FORMAT_BGRA:
		bpp := 3
		if f.Format != enums.FPDF_BITMAP_FORMAT_BGR {
			bpp = 4
		}
		out := image.NewNRGBA(image.Rect(0, 0, width, height))
		for y := 0; y < height; y++ {
			row := buf.Buffer[y*stride:]
			for x := 0; x < width; x++ {
				p := row[x*bpp:]
				o := out.Pix[y*out.Stride+x*4:]
				o[0], o[1], o[2], o[3] = p[2], p[1], p[0], 0xFF
				if f.Format == enums.FPDF_BITMAP_FORMAT_BGRA {
					o[3] = p[3]
				}
			}
		}
		return out
	}
	return nil
}

// metaText reads a document information entry.
func (d *pdfDoc) metaText(tag string) string {
	r, err := d.p.FPDF_GetMetaText(&requests.FPDF_GetMetaText{Document: d.doc, Tag: tag})
	if err != nil {
		return ""
	}
	return r.Value
}
